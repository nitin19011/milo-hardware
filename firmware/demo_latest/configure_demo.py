"""Generate the two Arduino config headers and synchronize shared support headers."""
import argparse,json,re,shutil
from pathlib import Path

ROOT=Path(__file__).resolve().parent

def configure(settings_path=None):
    path=Path(settings_path) if settings_path else ROOT/'demo_settings.local.json'
    if not path.exists():
        shutil.copy2(ROOT/'demo_settings.example.json',path)
    c=json.loads(path.read_text(encoding='utf-8-sig'))
    if not re.fullmatch(r'[a-z0-9-]{1,32}',c['session']):raise ValueError('Session must be 1..32 lowercase letters, digits or hyphens.')
    if len(c['ntp_servers'])!=3:raise ValueError('Provide three NTP servers.')
    for k in ['hand_source_id','mic_source_id','ultra96_source_id']:
        if not re.fullmatch(r'[a-z0-9-]{1,32}',c[k]):raise ValueError('Invalid source ID: '+k)
    if not 1<=c['max_clock_error_ms']<=1000:raise ValueError('Invalid clock tolerance')
    ca_path=Path(c['ca_file']);ca_path=ca_path if ca_path.is_absolute() else ROOT/ca_path
    ca=ca_path.read_text(encoding='utf-8').strip() if ca_path.is_file() else ''
    if ca and ('BEGIN CERTIFICATE' not in ca or 'PRIVATE KEY' in ca):raise ValueError('Supply the public CA certificate, not a private key.')
    if not c['tls'] and not c['allow_local_plaintext_test']:raise ValueError('Plaintext requires an explicit local-test flag.')
    values={'WIFI_SSID':c['wifi_ssid'],'WIFI_PASSWORD':c['wifi_password'],'MQTT_HOST':c['mqtt_host'],
            'SESSION':c['session'],'HAND_ID':c['hand_source_id'],'MIC_ID':c['mic_source_id'],'ULTRA96_ID':c['ultra96_source_id'],'ROOT_CA':ca}
    for name,role in [('GloveDemo','glove'),('MicDemo','mic')]:
        folder=ROOT/name;folder.mkdir(exist_ok=True)
        for p in (ROOT/'shared').glob('*.h'):shutil.copy2(p,folder/p.name)
        source=['#pragma once','// GENERATED by configure_demo.py; edit demo_settings.local.json instead.']
        for k,v in {**values,'MQTT_USERNAME':c[role+'_username'],'MQTT_PASSWORD':c[role+'_password'],'SOURCE_ID':c['hand_source_id' if role=='glove' else 'mic_source_id']}.items():
            source.append(f'const char {k}[] = {json.dumps(v)};')
        source += [f'const bool IS_GLOVE = {str(role=="glove").lower()};',f'const bool USE_TLS = {str(c["tls"]).lower()};',
                   f'const bool ALLOW_LOCAL_PLAINTEXT = {str(c["allow_local_plaintext_test"]).lower()};',
                   f'const uint16_t MQTT_PORT = {int(c["mqtt_port"])};',f'const uint32_t MAX_CLOCK_ERROR_MS = {int(c["max_clock_error_ms"])};',
                   f'const uint32_t MAX_AUDIO_TIMELINE_ERROR_US = {int(c["max_audio_timeline_error_us"])};',
                   'const char *const NTP_SERVERS[] = {'+', '.join(json.dumps(v) for v in c['ntp_servers'])+'};']
        (folder/'DemoConfig.h').write_text('\n'.join(source)+'\n',encoding='utf-8')
    missing=[k for k in ['wifi_password','glove_password','mic_password'] if not c.get(k)]
    if c['tls'] and not ca:missing.append('public CA certificate: '+str(ca_path))
    print('Both sketch folders generated. No credentials printed.')
    print('Pending: '+', '.join(missing) if missing else 'Connection settings supplied. Upload BOTH sketches after configuration changes.')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--settings',type=Path);args=p.parse_args();configure(args.settings)
