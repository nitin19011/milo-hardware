"""Regenerate the mic configuration after changing the private Wi-Fi/settings file."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent
def configure():
    c=json.loads((ROOT/'voice_settings.local.json').read_text(encoding='utf-8-sig'))
    if c['tls'] or not c.get('allow_local_plaintext_test'):raise ValueError('This package uses the explicit local laptop broker mode.')
    ca=''
    values={'WIFI_SSID':c['wifi_ssid'],'WIFI_PASSWORD':c['wifi_password'],'MQTT_HOST':c['mqtt_host'],
      'SESSION':c['session'],'HAND_ID':c['hand_source_id'],'MIC_ID':c['mic_source_id'],
      'ULTRA96_ID':c['ultra96_source_id'],'ROOT_CA':ca,'MQTT_USERNAME':c['mic_username'],
      'MQTT_PASSWORD':c['mic_password'],'SOURCE_ID':c['mic_source_id']}
    out=['#pragma once','// Generated by configure_voice.py; private connection settings.']
    out += [f'const char {k}[] = {json.dumps(v)};' for k,v in values.items()]
    out += ['const bool IS_GLOVE=false, USE_TLS=false, ALLOW_LOCAL_PLAINTEXT=true;',
      f'const uint16_t MQTT_PORT={int(c["mqtt_port"])};',
      f'const uint32_t MAX_CLOCK_ERROR_MS={int(c["max_clock_error_ms"])};',
      f'const uint32_t MAX_AUDIO_TIMELINE_ERROR_US={int(c["max_audio_timeline_error_us"])};',
      'const char *const NTP_SERVERS[]={'+','.join(json.dumps(v) for v in c['ntp_servers'])+'};']
    (ROOT/'MicVoiceFast/DemoConfig.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
    print('Mic settings generated. Upload MicVoiceFast after any settings change.')
if __name__=='__main__':configure()
